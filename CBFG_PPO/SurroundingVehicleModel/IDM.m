function a = IDM(v, vLeader, gap, p)

deltaV = v - vLeader;

desiredGap = p.jamDistance ...
    + p.timeGap * v ...
    + (v * deltaV) / (2 * sqrt(p.maxAcceleration * p.maxDeceleration));

a = p.maxAcceleration * ...
    (1 ...
    - (v / p.desiredVelocity)^4 ...
    - (desiredGap / gap)^2);

end