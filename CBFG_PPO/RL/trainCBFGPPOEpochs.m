function [actorNetwork, criticNetwork, ...
    optimizerState, trainingInfo] = ...
    trainCBFGPPOEpochs( ...
    actorNetwork, criticNetwork, buffer, ...
    optimizerState, pRL)

if buffer.count == 0
    error("Experience buffer is empty.");
end

N = buffer.count;

numBatches = ceil( ...
    N / pRL.miniBatchSize);

totalUpdates = ...
    pRL.numEpoch * numBatches;

trainingInfo.actorLoss = ...
    zeros(1, totalUpdates);

trainingInfo.ppoLoss = ...
    zeros(1, totalUpdates);

trainingInfo.bcLoss = ...
    zeros(1, totalUpdates);

trainingInfo.criticLoss = ...
    zeros(1, totalUpdates);

trainingInfo.meanActorLoss = ...
    zeros(1, pRL.numEpoch);

trainingInfo.meanPPOLoss = ...
    zeros(1, pRL.numEpoch);

trainingInfo.meanBCLoss = ...
    zeros(1, pRL.numEpoch);

trainingInfo.meanCriticLoss = ...
    zeros(1, pRL.numEpoch);

updateCount = 0;

for epoch = 1:pRL.numEpoch

    indices = randperm(N);

    epochActorLoss = ...
        zeros(1, numBatches);

    epochPPOLoss = ...
        zeros(1, numBatches);

    epochBCLoss = ...
        zeros(1, numBatches);

    epochCriticLoss = ...
        zeros(1, numBatches);

    for batchIndex = 1:numBatches

        startIndex = ...
            (batchIndex - 1) ...
            * pRL.miniBatchSize + 1;

        endIndex = min( ...
            batchIndex * pRL.miniBatchSize, ...
            N);

        selectedIndex = ...
            indices(startIndex:endIndex);

        miniBuffer.observation = ...
            buffer.observation(:, selectedIndex);

        miniBuffer.action = ...
            buffer.action(:, selectedIndex);

        miniBuffer.correctedAction = ...
            buffer.correctedAction(:, selectedIndex);

        miniBuffer.logProbability = ...
            buffer.logProbability(selectedIndex);

        miniBuffer.advantage = ...
            buffer.advantage(selectedIndex);

        miniBuffer.return = ...
            buffer.return(selectedIndex);

        miniBuffer.correctionAmplitude = ...
            buffer.correctionAmplitude(selectedIndex);

        miniBuffer.interventionFlag = ...
            buffer.interventionFlag(selectedIndex);

        miniBuffer.count = ...
            length(selectedIndex);

        [actorNetwork, criticNetwork, ...
            optimizerState, lossInfo] = ...
            updateCBFGPPO( ...
            actorNetwork, ...
            criticNetwork, ...
            miniBuffer, ...
            optimizerState, ...
            pRL);

        updateCount = ...
            updateCount + 1;

        trainingInfo.actorLoss(updateCount) = ...
            lossInfo.actorLoss;

        trainingInfo.ppoLoss(updateCount) = ...
            lossInfo.ppoLoss;

        trainingInfo.bcLoss(updateCount) = ...
            lossInfo.bcLoss;

        trainingInfo.criticLoss(updateCount) = ...
            lossInfo.criticLoss;

        epochActorLoss(batchIndex) = ...
            lossInfo.actorLoss;

        epochPPOLoss(batchIndex) = ...
            lossInfo.ppoLoss;

        epochBCLoss(batchIndex) = ...
            lossInfo.bcLoss;

        epochCriticLoss(batchIndex) = ...
            lossInfo.criticLoss;

    end

    trainingInfo.meanActorLoss(epoch) = ...
        mean(epochActorLoss);

    trainingInfo.meanPPOLoss(epoch) = ...
        mean(epochPPOLoss);

    trainingInfo.meanBCLoss(epoch) = ...
        mean(epochBCLoss);

    trainingInfo.meanCriticLoss(epoch) = ...
        mean(epochCriticLoss);

end

trainingInfo.numEpoch = ...
    pRL.numEpoch;

trainingInfo.numBatches = ...
    numBatches;

trainingInfo.totalUpdates = ...
    updateCount;

end