function [uSafe, deltaU, exitflag] = CBFController( ...
    xEgo, xSur, xSurNext, uMPC, road, pMPC, pCBF)

deltaU0 = zeros(2, 1);

lb = pMPC.uMin - uMPC;
ub = pMPC.uMax - uMPC;

objective = @(deltaU) norm(deltaU);

nonlcon = @(deltaU) cbfConstraints( ...
    deltaU, xEgo, xSur, xSurNext, ...
    uMPC, road, pMPC, pCBF);

options = optimoptions('fmincon', ...
    'Algorithm', 'sqp', ...
    'Display', 'none');

[deltaU, ~, exitflag] = fmincon( ...
    objective, deltaU0, ...
    [], [], [], [], ...
    lb, ub, nonlcon, options);

uSafe = uMPC + deltaU;

end