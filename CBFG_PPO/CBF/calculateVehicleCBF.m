function h0 = calculateVehicleCBF(xEgo, xSur, p)

egoPosition = xEgo(1:2);
surPosition = xSur(1:2);

egoHeading = xEgo(4);
surHeading = xSur(4);

lEgo = ellipseDistance( ...
    egoPosition, ...
    egoHeading, ...
    surPosition, ...
    p.egoEllipseA, ...
    p.egoEllipseB);

lSur = ellipseDistance( ...
    surPosition, ...
    surHeading, ...
    egoPosition, ...
    p.surEllipseA, ...
    p.surEllipseB);

centerDistance = norm(egoPosition - surPosition);

h0 = centerDistance - lEgo - lSur;

end