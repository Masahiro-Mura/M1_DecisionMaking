clear;
clc;

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(projectRoot));

clipFactor = 0.2;

%% Case 1: No intervention

probabilityRatio = dlarray([ ...
    1.1, ...
    0.9, ...
    1.0 ...
]);

advantage = dlarray([ ...
    1.0, ...
    0.5, ...
   -0.2 ...
]);

policyAction = dlarray([
    0.2, 0.1, -0.1;
    0.0, 0.2,  0.1
]);

correctedAction = policyAction;

correctionAmplitude = dlarray([ ...
    0.0, ...
    0.0, ...
    0.0 ...
]);

interventionFlag = [ ...
    0, ...
    0, ...
    0 ...
];

[actorLoss1, ppoLoss1, bcLoss1] = cbfGuidedLoss( ...
    probabilityRatio, ...
    advantage, ...
    policyAction, ...
    correctedAction, ...
    correctionAmplitude, ...
    interventionFlag, ...
    clipFactor);

assert(isfinite(extractdata(actorLoss1)));
assert(isfinite(extractdata(ppoLoss1)));
assert(isfinite(extractdata(bcLoss1)));

assert(abs(extractdata(bcLoss1)) < 1e-10);

disp("Case 1 passed.");

%% Case 2: Intervention only

probabilityRatio = dlarray([ ...
