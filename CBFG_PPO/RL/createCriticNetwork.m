function criticNetwork = createCriticNetwork(pRL)

layers = [
    featureInputLayer( ...
        pRL.observationDimension, ...
        'Normalization', 'none', ...
        'Name', 'observation')

    fullyConnectedLayer( ...
        pRL.criticHiddenUnits(1), ...
        'Name', 'critic_fc1')

    reluLayer( ...
        'Name', 'critic_relu1')

    fullyConnectedLayer( ...
        pRL.criticHiddenUnits(2), ...
        'Name', 'critic_fc2')

    reluLayer( ...
        'Name', 'critic_relu2')

    fullyConnectedLayer( ...
        1, ...
        'Name', 'stateValue')
];

criticNetwork = dlnetwork(layers);

end