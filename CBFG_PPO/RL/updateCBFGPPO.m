function [actorNetwork, criticNetwork, optimizerState, lossInfo] = ...
    updateCBFGPPO( ...
    actorNetwork, criticNetwork, buffer, ...
    optimizerState, pRL)

if buffer.count == 0
    error("Experience buffer is empty.");
end

if ~isfield(pRL, 'clipFactor')
    error("pRL.clipFactor is not defined.");
end

N = buffer.count;
batchSize = min(pRL.miniBatchSize, N);

index = randperm(N, batchSize);

batch.observation = dlarray( ...
    single(buffer.observation(:, index)), ...
    'CB');

batch.action = dlarray( ...
    single(buffer.action(:, index)), ...
    'CB');

batch.correctedAction = dlarray( ...
    single(buffer.correctedAction(:, index)), ...
    'CB');

batch.oldLogProbability = dlarray( ...
    single(buffer.logProbability(index)), ...
    'CB');

batch.advantage = dlarray( ...
    single(buffer.advantage(index)), ...
    'CB');

batch.return = dlarray( ...
    single(buffer.return(index)), ...
    'CB');

batch.correctionAmplitude = dlarray( ...
    single(buffer.correctionAmplitude(index)), ...
    'CB');

batch.interventionFlag = ...
    buffer.interventionFlag(index);

[actorGradients, criticGradients, ...
    actorLoss, ppoLoss, bcLoss, criticLoss] = ...
    dlfeval( ...
    @calculateCBFGGradients, ...
    actorNetwork, ...
    criticNetwork, ...
    batch, ...
    pRL);

if isempty(optimizerState)

    optimizerState.actorAverage = [];
    optimizerState.actorAverageSq = [];

    optimizerState.criticAverage = [];
    optimizerState.criticAverageSq = [];

    optimizerState.iteration = 0;

end

optimizerState.iteration = ...
    optimizerState.iteration + 1;

[actorNetwork, ...
    optimizerState.actorAverage, ...
    optimizerState.actorAverageSq] = ...
    adamupdate( ...
    actorNetwork, ...
    actorGradients, ...
    optimizerState.actorAverage, ...
    optimizerState.actorAverageSq, ...
    optimizerState.iteration, ...
    pRL.learningRate);

[criticNetwork, ...
    optimizerState.criticAverage, ...
    optimizerState.criticAverageSq] = ...
    adamupdate( ...
    criticNetwork, ...
    criticGradients, ...
    optimizerState.criticAverage, ...
    optimizerState.criticAverageSq, ...
    optimizerState.iteration, ...
    pRL.learningRate);

lossInfo.actorLoss = extractdata(actorLoss);
lossInfo.ppoLoss = extractdata(ppoLoss);
lossInfo.bcLoss = extractdata(bcLoss);
lossInfo.criticLoss = extractdata(criticLoss);

end