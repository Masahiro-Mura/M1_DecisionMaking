function [nextObservation, reward, isDone, loggedSignals] = ...
    rlStep(action, loggedSignals, pEnv, pMPC, pCBF, pIDM, pRL)

state = loggedSignals.state;

vRef = pRL.referenceVelocityMin ...
    + (action(1) + 1) / 2 ...
    * (pRL.referenceVelocityMax - pRL.referenceVelocityMin);

thetaRef = pRL.referenceHeadingMin ...
    + (action(2) + 1) / 2 ...
    * (pRL.referenceHeadingMax - pRL.referenceHeadingMin);

zRef = [
    vRef;
    thetaRef
];

[stateNext, uMPC, uSafe, deltaU] = stepEnvironment( ...
    state, zRef, pMPC, pCBF, pIDM);

[isDone, isSuccess, isFail] = checkTermination( ...
    stateNext.xEgo, ...
    stateNext.xSur, ...
    stateNext.stepCount, ...
    stateNext.road, ...
    pEnv, ...
    pCBF);

dx = stateNext.xSur(1, :) - stateNext.xEgo(1);

frontIndex = dx > 0;
rearIndex = dx < 0;

if any(frontIndex)
    dP = min(dx(frontIndex));
else
    dP = inf;
end

if any(rearIndex)
    dF = min(abs(dx(rearIndex)));
else
    dF = inf;
end

reward = calculateReward( ...
    stateNext.xEgo, ...
    dP, ...
    dF, ...
    thetaRef, ...
    state.thetaRefPrev, ...
    isSuccess, ...
    isFail, ...
    stateNext.road, ...
    pRL);

observation = getObservation( ...
    stateNext.xEgo, ...
    stateNext.xSur, ...
    stateNext.aSur, ...
    stateNext.road);

nextObservation = normalizeObservation( ...
    observation, pRL);

correctionAmplitude = norm(deltaU);

interventionFlag = ...
    correctionAmplitude > pRL.interventionThreshold;

loggedSignals.state = stateNext;

loggedSignals.rlAction = action;
loggedSignals.referenceAction = zRef;

loggedSignals.uMPC = uMPC;
loggedSignals.uSafe = uSafe;
loggedSignals.deltaU = deltaU;

loggedSignals.correctionAmplitude = ...
    correctionAmplitude;

loggedSignals.interventionFlag = ...
    interventionFlag;

end