function [actorGradients, criticGradients, ...
    actorLoss, ppoLoss, bcLoss, criticLoss] = ...
    calculateCBFGGradients( ...
    actorNetwork, criticNetwork, batch, pRL)

[actionMean, actionStd] = forward( ...
    actorNetwork, ...
    batch.observation, ...
    'Outputs', {'actionMean', 'actionStd'});

actionStd = actionStd + 1e-6;

logProbability = -0.5 * ( ...
    ((batch.action - actionMean) ./ actionStd).^2 ...
    + 2 * log(actionStd) ...
    + log(2 * pi));

logProbability = sum(logProbability, 1);

probabilityRatio = exp( ...
    logProbability ...
    - batch.oldLogProbability);

[actorLossRaw, ppoLoss, bcLoss] = ...
    cbfGuidedLoss( ...
    probabilityRatio, ...
    batch.advantage, ...
    actionMean, ...
    batch.correctedAction, ...
    batch.correctionAmplitude, ...
    batch.interventionFlag, ...
    pRL.clipFactor);

actorLoss = ...
    pRL.actorLossCoefficient * actorLossRaw;

valuePrediction = forward( ...
    criticNetwork, ...
    batch.observation);

criticLossRaw = mean( ...
    (valuePrediction - batch.return).^2, ...
    'all');

criticLoss = ...
    pRL.criticLossCoefficient * criticLossRaw;

actorGradients = dlgradient( ...
    actorLoss, ...
    actorNetwork.Learnables);

criticGradients = dlgradient( ...
    criticLoss, ...
    criticNetwork.Learnables);

end