%% Case 3: Mixed batch

probabilityRatio = dlarray([ ...
    1.1, ...
    0.9, ...
    1.0, ...
    1.2 ...
]);

advantage = dlarray([ ...
    1.0, ...
    0.5, ...
   -0.2, ...
    0.8 ...
]);

policyAction = dlarray([
    0.2,  0.1, -0.1, 0.0;
    0.0,  0.2,  0.1, 0.1
]);

correctedAction = dlarray([
    0.2,  0.2, -0.1, 0.1;
    0.0,  0.3,  0.1, 0.2
]);

correctionAmplitude = dlarray([ ...
    0.0, ...
    0.1, ...
    0.0, ...
    0.1 ...
]);

interventionFlag = [ ...
    0, ...
    1, ...
    0, ...
    1 ...
];

[actorLoss3, ppoLoss3, bcLoss3] = cbfGuidedLoss( ...
