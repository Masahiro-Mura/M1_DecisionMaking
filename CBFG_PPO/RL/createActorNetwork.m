function actorNetwork = createActorNetwork(pRL)

commonLayers = [
    featureInputLayer( ...
        pRL.observationDimension, ...
        'Normalization', 'none', ...
        'Name', 'observation')

    fullyConnectedLayer( ...
        pRL.actorHiddenUnits(1), ...
        'Name', 'actor_fc1')

    reluLayer( ...
        'Name', 'actor_relu1')

    fullyConnectedLayer( ...
        pRL.actorHiddenUnits(2), ...
        'Name', 'actor_fc2')

    reluLayer( ...
        'Name', 'actor_relu2')
];

meanLayers = [
    fullyConnectedLayer( ...
        pRL.actionDimension, ...
        'Name', 'actionMean')
];

stdLayers = [
    fullyConnectedLayer( ...
        pRL.actionDimension, ...
        'Name', 'actionStdFC')

    softplusLayer( ...
        'Name', 'actionStd')
];

network = layerGraph(commonLayers);

network = addLayers( ...
    network, ...
    meanLayers);

network = addLayers( ...
    network, ...
    stdLayers);

network = connectLayers( ...
    network, ...
    'actor_relu2', ...
    'actionMean');

network = connectLayers( ...
    network, ...
    'actor_relu2', ...
    'actionStdFC');

actorNetwork = dlnetwork(network);

end