clear;
clc;

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(projectRoot));

pRL = rlParameters();

buffer = createExperienceBuffer(pRL);

assert(buffer.count == 0);

assert(isequal( ...
    size(buffer.observation), ...
    [pRL.observationDimension, pRL.bufferSize]));

assert(isequal( ...
    size(buffer.nextObservation), ...
    [pRL.observationDimension, pRL.bufferSize]));

assert(isequal( ...
    size(buffer.action), ...
    [pRL.actionDimension, pRL.bufferSize]));

assert(isequal( ...
    size(buffer.correctedAction), ...
    [pRL.actionDimension, pRL.bufferSize]));

%% Experience 1

observation1 = zeros( ...
    pRL.observationDimension, 1);

nextObservation1 = ones( ...
    pRL.observationDimension, 1);

action1 = [
    0.2;
   -0.1
];

correctedAction1 = [
    0.3;
   -0.05
];

reward1 = 1.5;
done1 = false;

correctionAmplitude1 = 0.1;
interventionFlag1 = true;

logProbability1 = -0.5;
value1 = 0.8;

buffer = storeExperience( ...
    buffer, ...
    observation1, ...
    nextObservation1, ...
    action1, ...
    correctedAction1, ...
    reward1, ...
    done1, ...
    correctionAmplitude1, ...
    interventionFlag1, ...
    logProbability1, ...
    value1);

assert(buffer.count == 1);

assert(isequal( ...
    buffer.observation(:, 1), ...
    observation1));

assert(isequal( ...
    buffer.nextObservation(:, 1), ...
    nextObservation1));

assert(isequal( ...
    buffer.action(:, 1), ...
    action1));

assert(isequal( ...
    buffer.correctedAction(:, 1), ...
    correctedAction1));

assert(buffer.reward(1) == reward1);
assert(buffer.done(1) == done1);

assert( ...
    buffer.correctionAmplitude(1) ...
    == correctionAmplitude1);

assert( ...
    buffer.interventionFlag(1) ...
    == interventionFlag1);

assert( ...
    buffer.logProbability(1) ...
    == logProbability1);

assert( ...
    buffer.value(1) ...
    == value1);

disp("Experience 1 passed.");

