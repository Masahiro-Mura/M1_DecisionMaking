function [actorNetwork, criticNetwork, trainingResult] = ...
    trainCBFGPPO(pEnv, pMPC, pCBF, pIDM, pRL)

actorNetwork = createActorNetwork(pRL);
criticNetwork = createCriticNetwork(pRL);

optimizerState = [];

totalTimesteps = 0;
episodeCount = 0;

trainingResult.episodeReward = [];
trainingResult.episodeSteps = [];
trainingResult.totalTimesteps = [];
trainingResult.meanActorLoss = [];
trainingResult.meanPPOLoss = [];
trainingResult.meanBCLoss = [];
trainingResult.meanCriticLoss = [];

while totalTimesteps < pRL.totalTimesteps

    episodeCount = episodeCount + 1;

    [observation, loggedSignals] = ...
        rlReset(pEnv, pRL);

    buffer = createExperienceBuffer(pRL);

    episodeReward = 0;
    isDone = false;

    while ~isDone && ...
            totalTimesteps < pRL.totalTimesteps && ...
            buffer.count < pRL.bufferSize

        observationDL = dlarray( ...
            single(observation), ...
            'CB');

        [actionMean, actionStd] = forward( ...
            actorNetwork, ...
            observationDL, ...
            'Outputs', {'actionMean', 'actionStd'});

        actionStd = actionStd + 1e-6;

        noise = randn( ...
            pRL.actionDimension, 1, ...
            'single');

        actionDL = ...
            actionMean + actionStd .* noise;

        action = double(extractdata(actionDL));

        action = max( ...
            min(action, pRL.actionMax), ...
            pRL.actionMin);

        actionForProbability = dlarray( ...
            single(action), ...
            'CB');

        logProbability = -0.5 * ( ...
            ((actionForProbability - actionMean) ./ actionStd).^2 ...
            + 2 * log(actionStd) ...
            + log(2 * pi));

        logProbability = ...
            sum(logProbability, 1);

        logProbability = ...
            extractdata(logProbability);

        valueDL = forward( ...
            criticNetwork, ...
            observationDL);

        value = extractdata(valueDL);

        [nextObservation, reward, isDone, loggedSignals] = ...
            rlStep( ...
            action, ...
            loggedSignals, ...
            pEnv, ...
            pMPC, ...
            pCBF, ...
            pIDM, ...
            pRL);

        correctionAmplitude = ...
            loggedSignals.correctionAmplitude;

        interventionFlag = ...
            loggedSignals.interventionFlag;

        if interventionFlag

            error([ ...
                "CBF intervention occurred. " ...
                "The mapping from the corrected MPC control " ...
                "input to the RL action space has not yet " ...
                "been defined."]);

        else

            correctedAction = action;

        end

        buffer = storeExperience( ...
            buffer, ...
            observation, ...
            nextObservation, ...
            action, ...
            correctedAction, ...
            reward, ...
            isDone, ...
            correctionAmplitude, ...
            interventionFlag, ...
            logProbability, ...
            value);

        observation = nextObservation;

        episodeReward = ...
            episodeReward + reward;

        totalTimesteps = ...
            totalTimesteps + 1;

    end

    if isDone

        lastValue = 0;

    else

        observationDL = dlarray( ...
            single(observation), ...
            'CB');

        lastValueDL = forward( ...
            criticNetwork, ...
            observationDL);

        lastValue = ...
            extractdata(lastValueDL);

    end

    buffer = calculateAdvantage( ...
        buffer, ...
        lastValue, ...
        pRL);

    [actorNetwork, criticNetwork, ...
        optimizerState, trainingInfo] = ...
        trainCBFGPPOEpochs( ...
        actorNetwork, ...
        criticNetwork, ...
        buffer, ...
        optimizerState, ...
        pRL);

    trainingResult.episodeReward(episodeCount) = ...
        episodeReward;

    trainingResult.episodeSteps(episodeCount) = ...
        buffer.count;

    trainingResult.totalTimesteps(episodeCount) = ...
        totalTimesteps;

    trainingResult.meanActorLoss(episodeCount) = ...
        mean(trainingInfo.meanActorLoss);

    trainingResult.meanPPOLoss(episodeCount) = ...
        mean(trainingInfo.meanPPOLoss);

    trainingResult.meanBCLoss(episodeCount) = ...
        mean(trainingInfo.meanBCLoss);

    trainingResult.meanCriticLoss(episodeCount) = ...
        mean(trainingInfo.meanCriticLoss);

    fprintf( ...
        "Episode %d | Steps %d | Total %d | Reward %.3f\n", ...
        episodeCount, ...
        buffer.count, ...
        totalTimesteps, ...
        episodeReward);

end

trainingResult.optimizerState = ...
    optimizerState;

trainingResult.numEpisodes = ...
    episodeCount;

end