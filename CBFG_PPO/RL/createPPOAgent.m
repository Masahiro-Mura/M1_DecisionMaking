function agent = createPPOAgent( ...
    observationInfo, actionInfo, pRL)

actorNetwork = createActorNetwork(pRL);
criticNetwork = createCriticNetwork(pRL);

actor = rlContinuousGaussianActor( ...
    actorNetwork, ...
    observationInfo, ...
    actionInfo, ...
    'ObservationInputNames', 'observation', ...
    'ActionMeanOutputNames', 'actionMean', ...
    'ActionStandardDeviationOutputNames', 'actionStd');

critic = rlValueFunction( ...
    criticNetwork, ...
    observationInfo, ...
    'ObservationInputNames', 'observation');

actorOptimizer = rlOptimizerOptions( ...
    'LearnRate', pRL.learningRate);

criticOptimizer = rlOptimizerOptions( ...
    'LearnRate', pRL.learningRate);

agentOptions = rlPPOAgentOptions( ...
    'ExperienceHorizon', pRL.bufferSize, ...
    'MiniBatchSize', pRL.miniBatchSize, ...
    'NumEpoch', pRL.numEpoch, ...
    'DiscountFactor', pRL.discountFactor, ...
    'ActorOptimizerOptions', actorOptimizer, ...
    'CriticOptimizerOptions', criticOptimizer);

agent = rlPPOAgent( ...
    actor, ...
    critic, ...
    agentOptions);

end